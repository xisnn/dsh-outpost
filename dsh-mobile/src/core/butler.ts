/**
 * 给用户消息尾部加上模式标记。
 *
 * ## 为什么不推荐用了
 *
 * 这个函数会把 `〔模式:闲聊〕` 拼到**每一条**用户消息后面。
 * 100 轮对话就是 100 个标记，全都会进上下文、进 token 计费，
 * 而且模型每次都要重新读一遍「现在是闲聊模式」这个信息 —— 冗余。
 *
 * 更好的做法是 `modeSwitchMessage()`：只在**真正切换**的那一次
 * 补一条系统消息。日常消息不带任何标记。
 *
 * 保留这个函数是因为它对「单条消息自带上下文」这种场景确实更稳
 * （不依赖上一条消息有没有被模型记住），可以按需用。
 */
export function withModeTag(text: string, mode: ButlerMode): string {
  return `${text}〔模式:${mode === 'plan' ? '计划' : '闲聊'}〕`;
}

/**
 * 生成一条「模式切换」系统指令。
 *
 * 只在用户**真的切换模式**时发一次，之后的消息不再带任何标记。
 * 相比「每条消息都带标记」：
 *   · 省 token（100 轮省 100 个标记）
 *   · 上下文更干净（模型不用反复确认模式）
 *
 * fold 层见到 `〔模式切换〕` 前缀会把它从界面里滤掉，用户看不到。
 */
export function modeSwitchMessage(mode: ButlerMode): string {
  return mode === 'plan'
    ? `${BUTLER_MODE_MARK}现在切到「计划模式」：接下来先给方案，等用户确认再动手。`
    : `${BUTLER_MODE_MARK}现在切到「闲聊模式」：不要问方案，直接干。轻活自己动手，重活派队员。`;
}

/** 这条消息是不是「模式切换指令」（旧版本兼容用） */
export function isModeSwitch(text: string): boolean {
  return text.trimStart().startsWith(BUTLER_MODE_MARK);
}
